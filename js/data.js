// какую пользу обещают человеку, сколько он заплатит, когда действует
// предложение, какие ограничения есть и соответствует ли обещание результату.
//
// Типы кейсов:
//   корректное предложение      — текст соответствует условиям;
//   манипуляция / подача        — давление, одностороннее сравнение, история;
//   дарк-паттерн                — ложный факт или обещание, расходящееся с
//                                 условиями продукта.
//
// Схема кейса:
//   id        — число, уникальное
//   title     — короткое название
//   type      — подпись типа рядом с «Разбираем текст»
//   screen    — что показываем на экране телефона:
//     format     — banner / message (письмо) / push / landing / story
//     app        — отправитель / название сервиса
//     tint       — цветовая тема экрана
//     icon       — эмодзи
//     header     — { title } (заголовок или тема письма)
//     paragraphs — массив абзацев основного текста
//     cta        — текст кнопки
//     action     — подпись «Действие при нажатии» для пуша
//     cards      — карточки (например, тарифы на лендинге)
//     stories    — массив текстов кадров для серии сторис
//     popup      — { title, text } — попап при нажатии на кнопку
//   context   — условия задания: факты для редактора
//   question  — вопрос к участнику
//   options   — варианты { text, isCorrect } (isCorrect ровно у одного)
//   breakdown — разбор:
//     проблемное предложение: { type, problem, fix, example }
//       fix     — рекомендация
//       example — исправленный пример в том же формате (экран)
//     корректное предложение: { type, ok }
// ============================================================================

